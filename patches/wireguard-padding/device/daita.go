func (daita *MaybenotDaita) event(peer *Peer, eventType EventType, machine uint64) {
	if daita == nil {
		return
	}

	event := Event{
		Machine:   machine,
		EventType: eventType,
	}

	daita.eventsCloseLock.RLock()
	defer daita.eventsCloseLock.RUnlock()

	if daita.eventsClosed {
		return
	}

	select {
	case daita.events <- event:
	default:
		peer.device.log.Verbosef("Dropped DAITA event %v due to full buffer", event.EventType)
	}
}

func injectPadding(action Action, peer *Peer) {
	if action.ActionType != C.MaybenotAction_SendPadding {
		peer.device.log.Errorf("Got unknown action type %v", action.ActionType)
		return
	}
	daita := peer.getDaita()
	if daita == nil || !peer.isRunning.Load() {
		return
	}

	if action.Replace && peer.HasReplaceablePackets() && daita.maySend(action.Bypass) {
		peer.ReplacedPacketsInc()
		daita.PaddingSent(peer, action.Machine)
		return
	}

	// Padding alone must never start a handshake: an idle tunnel stays quiet.
	if keypair := peer.keypairs.Current(); keypair == nil || time.Since(keypair.created) >= RejectAfterTime {
		return
	}

	// StagePackets makes room by dropping the oldest batches, which would be real packets; drop the padding instead.
	if peer.queue.stagedPackets.Load() >= MaxStagedPackets || len(peer.queue.staged) == cap(peer.queue.staged) {
		return
	}

	// Never wait for the pools or queues: Peer.Stop waits for this goroutine.
	elem, ok := peer.device.TryNewOutboundElement()
	if !ok {
		return
	}
	elems, ok := peer.device.TryGetOutboundElementsContainer()
	if !ok {
		peer.device.PutMessageBuffer(elem.buffer)
		peer.device.PutOutboundElement(elem)
		return
	}
	elem.daitaPadding = true

	size := uint16(peer.device.tun.mtu.Load())
	elem.packet = elem.buffer[MessageTransportHeaderSize : MessageTransportHeaderSize+int(size)]
	clear(elem.packet)
	elem.packet[0] = DaitaPaddingMarker
	binary.BigEndian.PutUint16(elem.packet[DaitaOffsetTotalLength:DaitaOffsetTotalLength+2], size)

	elems.elems = append(elems.elems, elem)
	// A block with bypass holds non-bypass padding for release with the real packets; bypass-flagged
	// padding leaves at once (it is the confounder a blocking defense sends while it holds traffic).
	if !daita.maySend(action.Bypass) && daita.holdPadding(elem, action.Machine) {
		peer.device.PutOutboundElementsContainer(elems)
		return // PaddingSent fires at the release, when the packet actually leaves
	}
	peer.StagePackets(elems)
	peer.sendStagedPackets(false)
	daita.PaddingSent(peer, action.Machine)
}

func (daita *MaybenotDaita) runEventLoop(peer *Peer) {
	defer func() {
		C.maybenot_stop(daita.maybenot)
		close(daita.loopDone)
		daita.stopping.Done()
		daita.logger.Verbosef("%v - DAITA: event handler - stopped", peer)
	}()

	events := make([]Event, len(daita.events))

	for {
		events = events[:0]

		event, more := <-daita.events
		if !more {
			return
		}

		events = append(events, event)

		// Drain remaining events
	HandleEvents:
		for {
			select {
			case event, more := <-daita.events:
				if !more {
					daita.logger.Verbosef("%v - DAITA: dropping %d unhandled events", peer, len(events))
					return
				}
				events = append(events, event)

				// Make sure not to exceed the maximum C buffer capacity
				if len(events) >= len(daita.eventsCBuf) {
					break HandleEvents
				}
			default:
				break HandleEvents
			}
		}

		daita.handleEvents(events, peer)
	}
}

func (daita *MaybenotDaita) handleEvents(event []Event, peer *Peer) {
	for _, cAction := range daita.maybenotEventToActions(event) {
		action := cActionToGo(cAction)

		switch action.ActionType {
		case C.MaybenotAction_Cancel:
			machine := action.Machine

			switch action.Timer {
			case C.MaybenotTimer_Action:
				daita.stopPaddingTimer(machine)
			case C.MaybenotTimer_Internal:
				daita.stopMachineTimer(machine)
			case C.MaybenotTimer_All:
				daita.stopMachineTimer(machine)
				daita.stopPaddingTimer(machine)
			}

		case C.MaybenotAction_SendPadding:
			timer, paddingWasQueued := daita.paddingQueue[action.Machine]
			daita.reserveSlot(timer, paddingWasQueued)

			daita.paddingQueue[action.Machine] =
				time.AfterFunc(action.Timeout, func() {
					defer daita.stopping.Done()
					injectPadding(action, peer)
				})
		case C.MaybenotAction_BlockOutgoing:
			daita.scheduleBlock(action, peer)
		case C.MaybenotAction_UpdateTimer:
			timer, timerWasQueued := daita.machineTimers[action.Machine]

			var startNewTimer bool
			if !timerWasQueued || action.Replace {
				// Always start timer if it does not exist or if the replace flag is set
				startNewTimer = true
			} else {
				now := time.Now()
				// Replace timer if it (should have) already fired (completeAt - now is negative)
				// or in general if the action duration is greater than the time left
				startNewTimer = action.Duration > timer.completeAt.Sub(now)
			}

			// Replace or start new timer
			if startNewTimer {
				daita.reserveSlot(timer, timerWasQueued)

				daita.timerBegin(peer, action.Machine)
				daita.machineTimers[action.Machine] =
					newMachineTimer(action.Duration, func() {
						// Decrement wait group counter
						defer daita.stopping.Done()

						daita.timerEnd(peer, action.Machine)
					})
			}
		}
	}
}

// scheduleBlock (re)arms the machine's pending block timer: last wins. When it fires, the block begins.
func (daita *MaybenotDaita) scheduleBlock(action Action, peer *Peer) {
	daita.blocksMu.Lock()
	timer, was := daita.blockScheduled[action.Machine]
	daita.reserveSlot(timer, was)
	daita.blockScheduled[action.Machine] = time.AfterFunc(action.Timeout, func() {
		defer daita.stopping.Done()
		daita.fireBlock(action, peer)
	})
	daita.blocksMu.Unlock()
}

// fireBlock starts or replaces the machine's block. Blocking is global per the framework's model: the
// first active block emits BlockingBegin{machine} and BlockingEnd comes only when the last one ends.
// A replace block always proceeds (the framework allows it during active blocking); without replace,
// a second block from the same machine is dropped. The end timer carries its deadline: a later extend
// replaces the timer, and a stale firing checks against the map before ending anything.
func (daita *MaybenotDaita) fireBlock(action Action, peer *Peer) {
	daita.blocksMu.Lock()
	if _, was := daita.blocks[action.Machine]; was && !action.Replace {
		daita.blocksMu.Unlock()
		return
	}
	wasEmpty := len(daita.blocks) == 0
	deadline := time.Now().Add(action.Duration)
	daita.blocks[action.Machine] = blockState{deadline: deadline, bypass: action.Bypass}
	daita.blockCount.Store(int32(len(daita.blocks)))
	allBypass := true
	for _, b := range daita.blocks {
		if !b.bypass {
			allBypass = false
		}
	}
	daita.blockBypass.Store(allBypass)
	// the end timer lives in the same critical section: Close iterates these maps under blocksMu
	timer, was := daita.blockEnd[action.Machine]
	daita.reserveSlot(timer, was)
	daita.blockEnd[action.Machine] = time.AfterFunc(action.Duration, func() {
		defer daita.stopping.Done()
		daita.endBlock(action.Machine, deadline, peer)
	})
	daita.blocksMu.Unlock()
	if wasEmpty {
		daita.event(peer, BlockingBegin, action.Machine)
	}
}

// endBlock ends the machine's block if its deadline is still the current one (an extend replaced the
// timer). BlockingEnd comes only when the last active block ended, followed by the release of every
// held packet as one burst.
func (daita *MaybenotDaita) endBlock(machine uint64, deadline time.Time, peer *Peer) {
	daita.blocksMu.Lock()
	if cur, was := daita.blocks[machine]; !was || !cur.deadline.Equal(deadline) {
		daita.blocksMu.Unlock()
		return
	}
	delete(daita.blocks, machine)
	daita.blockCount.Store(int32(len(daita.blocks)))
	last := len(daita.blocks) == 0
	daita.blocksMu.Unlock()
	if last {
		daita.event(peer, BlockingEnd, 0)
		daita.releaseHeld(peer)
	}
}

// isBlocked reports whether the peer currently holds outgoing traffic.
func (daita *MaybenotDaita) isBlocked() bool { return daita.blockCount.Load() > 0 }

// maySend reports whether a padding action may leave during an active block: a block with bypass lets
// bypass-flagged padding through, and everything else is held to merge with the release.
func (daita *MaybenotDaita) maySend(bypass bool) bool {
	return !daita.isBlocked() || (bypass && daita.blockBypass.Load())
}

// blockHolds takes a TUN batch into the hold queue and reports whether it was held. The hold is bounded
// (blockHoldCap packets): past the cap the batch flows through unpadded rather than losing packets or
// pinning memory - a blocked peer under load degrades to unprotected instead of breaking.
func (daita *MaybenotDaita) blockHolds(elems []*QueueOutboundElement) bool {
	if daita.blockCount.Load() == 0 {
		return false
	}
	return daita.hold(elems...)
}

// hold appends to the hold queue unless the block has ended or the queue is full. The test runs under the lock: a
// hold decided before the block ended must not append into a drained queue and strand there until the next block.
func (daita *MaybenotDaita) hold(elems ...*QueueOutboundElement) bool {
	daita.heldMu.Lock()
	defer daita.heldMu.Unlock()
	if daita.blockCount.Load() == 0 || len(daita.held) >= blockHoldCap {
		return false
	}
	daita.held = append(daita.held, elems...)
	return true
}

// holdPadding takes a built padding packet into the hold queue while a block holds it, and reports
// whether it was held (false: the hold is full, the padding leaves at once like the fail-open path).
func (daita *MaybenotDaita) holdPadding(elem *QueueOutboundElement, machine uint64) bool {
	elem.daitaMachine = machine
	return daita.hold(elem)
}

// releaseHeld sends every held packet as one burst at the end of the last active block. NormalSent
// fires here, not at the TUN read: the machines must see the packets as sent when they actually are,
// and held padding fires PaddingSent here for the same reason.
func (daita *MaybenotDaita) releaseHeld(peer *Peer) {
	daita.heldMu.Lock()
	held := daita.held
	daita.held = nil
	daita.heldMu.Unlock()
	for len(held) > 0 {
		n := min(len(held), releaseBatch)
		batch := held[:n]
		held = held[n:]
		if !peer.isRunning.Load() {
			for _, elem := range batch {
				peer.device.PutMessageBuffer(elem.buffer)
				peer.device.PutOutboundElement(elem)
			}
			continue
		}
		// Reported before a packet is staged: any sender may then take it and return it to the pool, which reuses it.
		report := func(elem *QueueOutboundElement) {
			if elem.daitaPadding {
				daita.PaddingSent(peer, elem.daitaMachine)
			} else {
				daita.NormalSent(peer)
			}
		}
		if container, ok := peer.device.TryGetOutboundElementsContainer(); ok {
			for _, elem := range batch {
				report(elem)
			}
			container.elems = append(container.elems, batch...)
			peer.StagePackets(container)
		} else {
			// fail-open: no container from the pool, so the held packets leave one by one; one that gets none
			// returns its buffer and is not reported
			for _, elem := range batch {
				one, ok := peer.device.TryGetOutboundElementsContainer()
				if !ok {
					peer.device.PutMessageBuffer(elem.buffer)
					peer.device.PutOutboundElement(elem)
					continue
				}
				report(elem)
				one.elems = append(one.elems, elem)
				peer.StagePackets(one)
			}
		}
		peer.SendStagedPackets()
	}
}

// dropHeld discards held packets (peer stopped or reset): their buffers return to the pools.
func (daita *MaybenotDaita) dropHeld(peer *Peer) {
	daita.heldMu.Lock()
	held := daita.held
	daita.held = nil
	daita.heldMu.Unlock()
	for _, elem := range held {
		peer.device.PutMessageBuffer(elem.buffer)
		peer.device.PutOutboundElement(elem)
	}
}

func (daita *MaybenotDaita) stopMachineTimer(machine uint64) {
	if timer, ok := daita.machineTimers[machine]; ok {
		daita.stopTimer(timer)
	}
}

func (daita *MaybenotDaita) stopPaddingTimer(machine uint64) {
	if queuedPadding, ok := daita.paddingQueue[machine]; ok {
		daita.stopTimer(queuedPadding)
	}
}

// stoppable is a *time.Timer or a *MachineTimer. Every armed one owns a slot of the wait group, which its
// callback releases when it runs.
type stoppable interface{ Stop() bool }

// stopTimer stops a pending timer; one that never runs releases its slot here.
func (daita *MaybenotDaita) stopTimer(t stoppable) {
	if t.Stop() {
		daita.stopping.Done()
	}
}

// reserveSlot is called before a timer replaces old, which is nil when existed is false. Stopping a pending old
// timer hands its slot to the new one; otherwise the new timer needs a fresh slot.
func (daita *MaybenotDaita) reserveSlot(old stoppable, existed bool) {
	if !existed || !old.Stop() {
		daita.stopping.Add(1)
	}
}

func (daita *MaybenotDaita) maybenotEventToActions(events []Event) []C.MaybenotAction {
	for i := 0; i < len(events); i++ {
		daita.eventsCBuf[i] = C.MaybenotEvent{
			machine:    C.uintptr_t(events[i].Machine),
			event_type: C.uint32_t(events[i].EventType),
		}
	}

	var actionsWritten C.uintptr_t

	firstElem := (*C.MaybenotEvent)(unsafe.SliceData(daita.eventsCBuf))
	result := C.maybenot_on_events(daita.maybenot, firstElem, C.uintptr_t(len(events)), &daita.newActionsBuf[0], &actionsWritten)
	if result != 0 {
		daita.logger.Errorf("Failed to handle event as it was a null pointer")
		return nil
	}

	newActions := daita.newActionsBuf[:actionsWritten]
	return newActions
}

func cActionToGo(action_c C.MaybenotAction) Action {
	switch action_c.tag {
	case C.MaybenotAction_Cancel:
		body := (*C.MaybenotAction_Cancel_Body)(unsafe.Pointer(&action_c.anon0[0]))
		return Action{
			ActionType: action_c.tag,
			Machine:    uint64(body.machine),
			Timer:      body.timer,
		}

	case C.MaybenotAction_SendPadding:
		body := (*C.MaybenotAction_SendPadding_Body)(unsafe.Pointer(&action_c.anon0[0]))
		return Action{
			ActionType: action_c.tag,
			Machine:    uint64(body.machine),
			Timeout:    maybenotDurationToGoDuration(body.timeout),
			Replace:    bool(body.replace),
			Bypass:     bool(body.bypass),
		}

	case C.MaybenotAction_BlockOutgoing:
		body := (*C.MaybenotAction_BlockOutgoing_Body)(unsafe.Pointer(&action_c.anon0[0]))
		return Action{
			ActionType: action_c.tag,
			Machine:    uint64(body.machine),
			Timeout:    maybenotDurationToGoDuration(body.timeout),
			Replace:    bool(body.replace),
			Bypass:     bool(body.bypass),
			Duration:   maybenotDurationToGoDuration(body.duration),
		}

	case C.MaybenotAction_UpdateTimer:
		body := (*C.MaybenotAction_UpdateTimer_Body)(unsafe.Pointer(&action_c.anon0[0]))
		return Action{
			ActionType: action_c.tag,
			Machine:    uint64(body.machine),
			Duration:   maybenotDurationToGoDuration(body.duration),
			Replace:    bool(body.replace),
		}

	default:
		panic("Unknown C.MaybenotAction tag")
	}
}

func maybenotDurationToGoDuration(duration C.MaybenotDuration) time.Duration {
	// let's just assume this is fine...
	nanoseconds := uint64(duration.secs)*1_000_000_000 + uint64(duration.nanos)
	return time.Duration(nanoseconds)
}
