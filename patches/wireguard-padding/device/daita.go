// MaybenotDaita runs the padding framework's event loop for one peer, for machines that only send padding.
type MaybenotDaita struct {
	// A ring of the peer's last real packet sizes: a dummy takes one, so a size filter cannot single it out.
	sizes       [64]atomic.Uint32
	sizesSeen   atomic.Uint64
	unknownOnce sync.Once

	events          chan Event
	eventsClosed    bool
	eventsCloseLock sync.RWMutex
	eventsCBuf      []C.MaybenotEvent
	maybenot        *C.MaybenotFramework
	newActionsBuf   []C.MaybenotAction
	paddingQueue    map[uint64]*time.Timer // Map from machine to queued padding packets
	logger          *Logger
	stopping        sync.WaitGroup // waitgroup for runEventLoop and the queued padding timers
	loopDone        chan struct{}
}

type Event struct {
	// The machine that generated the action that generated this event, if any.
	Machine   uint64
	EventType EventType
}

type Action struct {
	ActionType C.MaybenotAction_Tag

	// The maybenot machine that generated the action.
	// Should be propagated back by events generated by this action.
	Machine uint64

	// The time at which the action should be performed
	Timeout time.Duration

	// Replace says whether the action replaces the machine's previous one
	Replace bool
}

func (peer *Peer) EnableDaita(machines string, eventsCapacity uint, maxPaddingFrac float64, maxBlockingFrac float64) bool {
	peer.state.Lock()
	defer peer.state.Unlock()

	if !peer.isRunning.Load() || peer.daita.Load() != nil {
		return false
	}

	peer.device.log.Verbosef("Enabling DAITA for peer: %v", peer)

	mtu := peer.device.tun.mtu.Load()

	peer.device.log.Verbosef("MTU %v", mtu)
	var maybenot *C.MaybenotFramework
	c_machines := C.CString(machines)

	c_maxPaddingFrac := C.double(maxPaddingFrac)
	c_maxBlockingFrac := C.double(maxBlockingFrac)

	maybenot_result := C.maybenot_start(
		c_machines, c_maxPaddingFrac, c_maxBlockingFrac,
		&maybenot,
	)
	C.free(unsafe.Pointer(c_machines))

	if maybenot_result != 0 {
		peer.device.log.Errorf("Failed to initialize maybenot, code=%d", maybenot_result)
		return false
	}

	numMachines := C.maybenot_num_machines(maybenot)
	daita := MaybenotDaita{
		events:        make(chan Event, eventsCapacity),
		eventsCBuf:    make([]C.MaybenotEvent, eventsCapacity),
		maybenot:      maybenot,
		newActionsBuf: make([]C.MaybenotAction, numMachines),
		paddingQueue:  map[uint64]*time.Timer{},
		logger:        peer.device.log,
		loopDone:      make(chan struct{}),
	}

	daita.stopping.Add(1)
	go daita.runEventLoop(peer)

	var d Daita = &daita
	peer.daita.Store(&d)

	return true
}

// Stop the MaybenotDaita instance. It must not be used after calling this.
func (daita *MaybenotDaita) Close() {
	daita.logger.Verbosef("Waiting for DAITA routines to stop")

	daita.eventsCloseLock.Lock()
	close(daita.events)
	daita.eventsClosed = true
	daita.eventsCloseLock.Unlock()

	// The event loop is the only writer of the padding queue; read it only after it has returned.
	<-daita.loopDone

	for _, timer := range daita.paddingQueue {
		daita.stopTimer(timer)
	}
	daita.stopping.Wait()
	daita.logger.Verbosef("DAITA routines have stopped")
}

func (daita *MaybenotDaita) Event(peer *Peer, eventType EventType, machine uint64) {
	if daita == nil {
		return
	}

	event := Event{
		Machine:   machine,
		EventType: eventType,
	}

	daita.eventsCloseLock.RLock()
	defer daita.eventsCloseLock.RUnlock()

	if daita.eventsClosed {
		return
	}

	select {
	case daita.events <- event:
	default:
		peer.device.log.Verbosef("Dropped DAITA event %v due to full buffer", event.EventType)
	}
}

func (daita *MaybenotDaita) RecordSize(size int) {
	i := daita.sizesSeen.Add(1) - 1
	daita.sizes[i%uint64(len(daita.sizes))].Store(uint32(size))
}

// dummySize is a size drawn from the real packets the peer sent lately, or the smallest dummy before there were any.
func (daita *MaybenotDaita) dummySize(mtu int) int {
	n := min(daita.sizesSeen.Load(), uint64(len(daita.sizes)))
	if n == 0 {
		return int(DaitaHeaderLen)
	}
	size := int(daita.sizes[rand.N(n)].Load())
	return min(max(size, int(DaitaHeaderLen)), mtu)
}

func (daita *MaybenotDaita) injectPadding(action Action, peer *Peer) {
	if peer.getDaita() == nil || !peer.isRunning.Load() {
		return
	}

	if action.Replace && peer.HasReplaceablePackets() {
		peer.ReplacedPacketsInc()
		daita.Event(peer, PaddingSent, action.Machine)
		return
	}

	// Padding alone must never start a handshake: an idle tunnel stays quiet.
	if keypair := peer.keypairs.Current(); keypair == nil || time.Since(keypair.created) >= RejectAfterTime {
		return
	}

	// StagePackets makes room by dropping the oldest batches, which would be real packets; drop the padding instead.
	if peer.queue.stagedPackets.Load() >= MaxStagedPackets || len(peer.queue.staged) == cap(peer.queue.staged) {
		return
	}

	// Never wait for the pools or queues: Peer.Stop waits for this goroutine.
	elem, ok := peer.device.TryNewOutboundElement()
	if !ok {
		return
	}
	elems, ok := peer.device.TryGetOutboundElementsContainer()
	if !ok {
		peer.device.PutMessageBuffer(elem.buffer)
		peer.device.PutOutboundElement(elem)
		return
	}

	size := daita.dummySize(int(peer.device.tun.mtu.Load()))
	elem.packet = elem.buffer[MessageTransportHeaderSize : MessageTransportHeaderSize+size]
	clear(elem.packet)
	elem.packet[0] = DaitaPaddingMarker
	binary.BigEndian.PutUint16(elem.packet[DaitaOffsetTotalLength:DaitaOffsetTotalLength+2], uint16(size))
	elem.padding = true

	elems.elems = append(elems.elems, elem)
	peer.StagePackets(elems)
	peer.sendStagedPackets(false)
	daita.Event(peer, PaddingSent, action.Machine)
}

func (daita *MaybenotDaita) runEventLoop(peer *Peer) {
	defer func() {
		C.maybenot_stop(daita.maybenot)
		close(daita.loopDone)
		daita.stopping.Done()
		daita.logger.Verbosef("%v - DAITA: event handler - stopped", peer)
	}()

	events := make([]Event, len(daita.events))

	for {
		events = events[:0]

		event, more := <-daita.events
		if !more {
			return
		}

		events = append(events, event)

		// Drain remaining events
	HandleEvents:
		for {
			select {
			case event, more := <-daita.events:
				if !more {
					daita.logger.Verbosef("%v - DAITA: dropping %d unhandled events", peer, len(events))
					return
				}
				events = append(events, event)

				// Make sure not to exceed the maximum C buffer capacity
				if len(events) >= len(daita.eventsCBuf) {
					break HandleEvents
				}
			default:
				break HandleEvents
			}
		}

		daita.handleEvents(events, peer)
	}
}

func (daita *MaybenotDaita) handleEvents(event []Event, peer *Peer) {
	for _, cAction := range daita.maybenotEventToActions(event) {
		action, ok := cActionToGo(cAction)
		if !ok {
			daita.unknownOnce.Do(func() { daita.logger.Errorf("%v - DAITA: skipping actions other than SendPadding", peer) })
			continue
		}
		timer, paddingWasQueued := daita.paddingQueue[action.Machine]
		daita.reserveSlot(timer, paddingWasQueued)

		daita.paddingQueue[action.Machine] =
			time.AfterFunc(action.Timeout, func() {
				defer daita.stopping.Done()
				daita.injectPadding(action, peer)
			})
	}
}

func (daita *MaybenotDaita) maybenotEventToActions(events []Event) []C.MaybenotAction {
	for i := 0; i < len(events); i++ {
		daita.eventsCBuf[i] = C.MaybenotEvent{
			machine:    C.uintptr_t(events[i].Machine),
			event_type: C.uint32_t(events[i].EventType),
		}
	}

	var actionsWritten C.uintptr_t

	firstElem := (*C.MaybenotEvent)(unsafe.SliceData(daita.eventsCBuf))
	result := C.maybenot_on_events(daita.maybenot, firstElem, C.uintptr_t(len(events)), &daita.newActionsBuf[0], &actionsWritten)
	if result != 0 {
		daita.logger.Errorf("Failed to handle event as it was a null pointer")
		return nil
	}

	newActions := daita.newActionsBuf[:actionsWritten]
	return newActions
}

// cActionToGo reports false for any action but SendPadding; machines are data, and data must not stop the peer.
func cActionToGo(action_c C.MaybenotAction) (Action, bool) {
	if action_c.tag != C.MaybenotAction_SendPadding {
		return Action{}, false
	}
	body := (*C.MaybenotAction_SendPadding_Body)(unsafe.Pointer(&action_c.anon0[0]))
	return Action{
		ActionType: action_c.tag,
		Machine:    uint64(body.machine),
		Timeout:    maybenotDurationToGoDuration(body.timeout),
		Replace:    bool(body.replace),
	}, true
}

func maybenotDurationToGoDuration(duration C.MaybenotDuration) time.Duration {
	nanoseconds := uint64(duration.secs)*1_000_000_000 + uint64(duration.nanos)
	return time.Duration(nanoseconds)
}

// stopTimer stops a pending padding timer; one that never runs releases its slot here.
func (daita *MaybenotDaita) stopTimer(t *time.Timer) {
	if t.Stop() {
		daita.stopping.Done()
	}
}

// reserveSlot is called before a timer replaces old, which is nil when existed is false. Stopping a pending old
// timer hands its slot to the new one; otherwise the new timer needs a fresh slot.
func (daita *MaybenotDaita) reserveSlot(old *time.Timer, existed bool) {
	if !existed || !old.Stop() {
		daita.stopping.Add(1)
	}
}
